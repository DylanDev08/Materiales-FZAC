-- Administrable FZAC assistant knowledge with private quality feedback.
-- Additive and idempotent: no operational tables or existing rows are removed.

begin;

create table if not exists public.assistant_knowledge (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  title text not null check (char_length(title) between 2 and 100),
  topic text not null check (char_length(topic) between 2 and 60),
  intent text not null default 'store_policy' check (intent in (
    'greeting', 'delivery', 'payment', 'stock', 'price', 'estimate',
    'order_status', 'returns', 'store_policy', 'human', 'product_search', 'fallback'
  )),
  keywords text[] not null default '{}',
  phrases text[] not null default '{}',
  answer text not null check (char_length(answer) between 20 and 1200),
  alternate_answer text check (alternate_answer is null or char_length(alternate_answer) between 20 and 1200),
  source_label text not null check (char_length(source_label) between 2 and 100),
  source_href text not null check (source_href ~ '^/[A-Za-z0-9_?=&/%.-]*$' and source_href !~ '^//'),
  actions jsonb not null default '[]'::jsonb check (jsonb_typeof(actions) = 'array'),
  active boolean not null default true,
  version integer not null default 1 check (version > 0),
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists assistant_knowledge_active_topic_idx
on public.assistant_knowledge (active, topic, updated_at desc);

create table if not exists public.assistant_knowledge_versions (
  id bigint generated by default as identity primary key,
  knowledge_id uuid not null references public.assistant_knowledge(id) on delete cascade,
  version integer not null,
  snapshot jsonb not null,
  changed_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (knowledge_id, version)
);

create table if not exists public.assistant_feedback (
  id uuid primary key default gen_random_uuid(),
  trace_id uuid not null unique,
  conversation_id uuid references public.chat_conversations(id) on delete cascade,
  user_id uuid references auth.users(id) on delete set null,
  visitor_id uuid,
  knowledge_slug text,
  rating text not null check (rating in ('UP', 'DOWN')),
  created_at timestamptz not null default now(),
  check (user_id is not null or visitor_id is not null)
);

create index if not exists assistant_feedback_created_idx
on public.assistant_feedback (created_at desc);

create or replace function public.archive_assistant_knowledge_version()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.assistant_knowledge_versions (knowledge_id, version, snapshot, changed_by)
  values (old.id, old.version, to_jsonb(old), new.updated_by)
  on conflict (knowledge_id, version) do nothing;
  new.version := old.version + 1;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists archive_assistant_knowledge_version_trigger on public.assistant_knowledge;
create trigger archive_assistant_knowledge_version_trigger
before update on public.assistant_knowledge
for each row execute function public.archive_assistant_knowledge_version();

