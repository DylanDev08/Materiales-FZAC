on public.assistant_knowledge for all
using (public.is_admin())
with check (public.is_admin());

drop policy if exists "admin assistant knowledge versions read" on public.assistant_knowledge_versions;
create policy "admin assistant knowledge versions read"
on public.assistant_knowledge_versions for select
using (public.is_admin());

drop policy if exists "admin assistant feedback read" on public.assistant_feedback;
create policy "admin assistant feedback read"
on public.assistant_feedback for select
using (public.is_admin());

revoke all on table public.assistant_knowledge from anon, authenticated;
grant select on table public.assistant_knowledge to anon, authenticated;
grant all on table public.assistant_knowledge to service_role;

revoke all on table public.assistant_knowledge_versions from anon, authenticated;
grant select on table public.assistant_knowledge_versions to authenticated;
grant all on table public.assistant_knowledge_versions to service_role;

revoke all on table public.assistant_feedback from anon, authenticated;
grant select on table public.assistant_feedback to authenticated;
grant all on table public.assistant_feedback to service_role;

grant usage, select on sequence public.assistant_knowledge_versions_id_seq to service_role;

